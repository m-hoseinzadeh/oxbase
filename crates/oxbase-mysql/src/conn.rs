/// Items buffered between the reader task and the consumer.
const CHANNEL_CAPACITY: usize = 4;
/// Interval between repeated `KILL QUERY`s while a cancelled run is still reading.
pub const KILL_RETRY: Duration = Duration::from_millis(500);
/// How long after a cancel request the run keeps killing before it abandons the session (see
/// the module docs). Keeps the stream's `Cancelled` within the 5 s cancel contract.
pub const CANCEL_DEADLINE: Duration = Duration::from_secs(4);
/// Upper bound for opening one cancel side connection (also capped by the time left).
const KILL_CONNECT_TIMEOUT: Duration = Duration::from_secs(3);
/// Upper bound for one `KILL QUERY` reply; without a reply the session is abandoned.
const KILL_REPLY_TIMEOUT: Duration = Duration::from_secs(2);
/// Smallest reply wait, even when the deadline is closer.
const KILL_REPLY_MIN: Duration = Duration::from_millis(250);
/// Time an abandoned session gets for a clean `COM_QUIT` before its socket is dropped.
const ABANDON_CLOSE_GRACE: Duration = Duration::from_secs(1);
/// Deadline for the background `KILL CONNECTION` of an abandoned session.
const ABANDON_KILL_TIMEOUT: Duration = Duration::from_secs(30);

/// Notice code carrying the `AUTO_INCREMENT` id generated by a statement.
pub const LAST_INSERT_ID_CODE: &str = "last_insert_id";

type Sender = mpsc::Sender<Result<ResultItem>>;

fn lock<T>(m: &StdMutex<T>) -> MutexGuard<'_, T> {
    m.lock().unwrap_or_else(PoisonError::into_inner)
}

fn closed() -> Error {
    Error::connection("the connection is closed")
}

/// State shared by a connection, its transactions and its running statement tasks.
pub(crate) struct Shared {
    /// The session; `None` once closed.
    session: Arc<Mutex<Option<Conn>>>,
    /// Options for cancel side connections: the session's own (same dial address and TLS).
    side_opts: Opts,
    connection_id: u32,
    options: MySqlOptions,
    /// Token of the statement currently running, with its run number.
    running: StdMutex<Option<(u64, CancellationToken)>>,
    next_run: AtomicU64,
    /// Set when a [`MySqlTx`] was dropped without commit or rollback.
    needs_rollback: AtomicBool,
    /// Last non-zero `AUTO_INCREMENT` id, `0` for none.
    last_insert_id: AtomicU64,
}

impl Shared {
    fn begin_run(&self, token: CancellationToken) -> u64 {
        let id = self.next_run.fetch_add(1, Ordering::Relaxed);
        *lock(&self.running) = Some((id, token));
        id
    }

    fn end_run(&self, id: u64) {
        let mut running = lock(&self.running);
        if running.as_ref().is_some_and(|(r, _)| *r == id) {
            *running = None;
        }
    }

    fn cancel_running(&self) {
        if let Some((_, token)) = lock(&self.running).as_ref() {
            token.cancel();
        }
    }

    /// Rolls back a transaction whose [`MySqlTx`] was dropped, if any.
    async fn rollback_if_needed(&self, conn: &mut Conn) -> Result<()> {
        if self.needs_rollback.swap(false, Ordering::SeqCst) {
            conn.query_drop("ROLLBACK").await.map_err(map_error)?;
        }
        Ok(())
    }
}

/// An open MySQL or MariaDB session.
pub struct MySqlConnection {
    shared: Arc<Shared>,
    flavor: Flavor,
    version: ServerVersion,
    tls: bool,
    server: String,
    /// The connect-time default database (`ConnectParams::database`), if any.
    database: Option<String>,
}

impl fmt::Debug for MySqlConnection {
    // Hand-written: `mysql_async::Opts` / `Conn` print the password in their `Debug`.
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.debug_struct("MySqlConnection")
            .field("flavor", &self.flavor)
            .field("server", &self.server)
            .field("version", &self.version.raw())
            .field("connection_id", &self.shared.connection_id)
            .field("tls", &self.tls)
            .field("database", &self.database)
            .finish_non_exhaustive()
    }
}

impl MySqlConnection {
    pub(crate) fn new(
        conn: Conn,
        side_opts: Opts,
        options: MySqlOptions,
        flavor: Flavor,
        version: ServerVersion,
        tls: bool,
        server: String,
    ) -> Self {
        let connection_id = conn.id();
        Self {
            shared: Arc::new(Shared {
                session: Arc::new(Mutex::new(Some(conn))),
                side_opts,
                connection_id,
                options,
                running: StdMutex::new(None),
                next_run: AtomicU64::new(0),
                needs_rollback: AtomicBool::new(false),
                last_insert_id: AtomicU64::new(0),
            }),
            flavor,
            version,
            tls,
            server,
            database: None,
        }
    }

    /// Records the connect-time default database, reported by [`Connection::current_database`].
    /// An empty name means "none", as it does for the server.
    #[must_use]
    pub(crate) fn with_database(mut self, database: Option<String>) -> Self {
        self.database = database.filter(|d| !d.is_empty());
        self
    }

    /// Whether the server is MySQL or MariaDB (detected from its version string).
    pub fn flavor(&self) -> Flavor {
        self.flavor
    }

    /// The server's connection (thread) id, the target of `KILL QUERY`.
    pub fn connection_id(&self) -> u32 {
        self.shared.connection_id
    }

    /// The last non-zero `AUTO_INCREMENT` id generated on this connection, if any. Each statement
    /// that generates one also reports it as an info [`Notice`] with code
    /// [`LAST_INSERT_ID_CODE`].
    pub fn last_insert_id(&self) -> Option<u64> {
        match self.shared.last_insert_id.load(Ordering::Relaxed) {
            0 => None,
            id => Some(id),
        }
    }
}

#[async_trait]
impl Connection for MySqlConnection {
    fn engine(&self) -> Engine {
        self.flavor.engine()
    }

    fn server_version(&self) -> &ServerVersion {
        &self.version
    }

    fn tls_in_use(&self) -> bool {
        self.tls
    }

    fn current_database(&self) -> Option<String> {
        self.database.clone()
    }

    async fn execute(
        &self,
        sql: &str,
        params: &[Value],
        cancel: CancellationToken,
    ) -> Result<ResultStream> {
        execute(&self.shared, sql, params, cancel).await
    }

    async fn cancel_running(&self) -> Result<()> {
        self.shared.cancel_running();
        Ok(())
    }

    async fn begin(&self) -> Result<Box<dyn Tx>> {
        let mut guard = self.shared.session.lock().await;
        let conn = guard.as_mut().ok_or_else(closed)?;
        self.shared.rollback_if_needed(conn).await?;
        conn.query_drop("START TRANSACTION")
            .await
            .map_err(map_error)?;
        Ok(Box::new(MySqlTx {
            shared: Arc::clone(&self.shared),
            finished: AtomicBool::new(false),
        }))
    }

    async fn close(&self) -> Result<()> {
        // A running statement is cancelled first; its task releases the session when it is done.
        self.shared.cancel_running();
        let conn = self.shared.session.lock().await.take();
        if let Some(conn) = conn
            && let Err(e) = conn.disconnect().await
        {
            tracing::debug!(error = %e, "MySQL disconnect failed");
        }
        Ok(())
    }
}

/// A transaction started with `START TRANSACTION`.
struct MySqlTx {
    shared: Arc<Shared>,
    finished: AtomicBool,
}

impl MySqlTx {
    async fn finish(&self, sql: &str) -> Result<()> {
        let mut guard = self.shared.session.lock().await;
        let conn = guard.as_mut().ok_or_else(closed)?;
        self.finished.store(true, Ordering::SeqCst);
        conn.query_drop(sql).await.map_err(map_error)
    }
}

impl Drop for MySqlTx {
    fn drop(&mut self) {
        if self.finished.load(Ordering::SeqCst) {
            return;
        }
        // Roll back on the next use of the session, or right away when a runtime is available.
        self.shared.needs_rollback.store(true, Ordering::SeqCst);
        if let Ok(handle) = tokio::runtime::Handle::try_current() {
            let shared = Arc::clone(&self.shared);
            handle.spawn(async move {
                let mut guard = shared.session.lock().await;
                if let Some(conn) = guard.as_mut()
                    && let Err(e) = shared.rollback_if_needed(conn).await
                {
                    tracing::debug!(error = %e, "rollback of a dropped MySQL transaction failed");
                }
            });
        }
    }
}

#[async_trait]
impl Tx for MySqlTx {
    async fn execute(
        &self,
        sql: &str,
        params: &[Value],
        cancel: CancellationToken,
    ) -> Result<ResultStream> {
        if self.finished.load(Ordering::SeqCst) {
            return Err(Error::invalid_input("the transaction has already ended"));
        }
        execute(&self.shared, sql, params, cancel).await
    }

    async fn commit(self: Box<Self>) -> Result<()> {
        self.finish("COMMIT").await
    }

    async fn rollback(self: Box<Self>) -> Result<()> {
        self.finish("ROLLBACK").await
    }
}

/// Starts `sql` on the session and returns its result stream (see the module docs).
async fn execute(
    shared: &Arc<Shared>,
    sql: &str,
    params: &[Value],
    cancel: CancellationToken,
) -> Result<ResultStream> {
    if cancel.is_cancelled() {
        return Err(Error::Cancelled);
    }
    let params: Vec<MyValue> = params.iter().map(to_param).collect();
    let guard = tokio::select! {
        biased;
        () = cancel.cancelled() => return Err(Error::Cancelled),
        guard = Arc::clone(&shared.session).lock_owned() => guard,
    };
    if guard.is_none() {
        return Err(closed());
    }
    let token = cancel.child_token();
    let run = shared.begin_run(token.clone());
    let (tx, rx) = mpsc::channel(CHANNEL_CAPACITY);
    tokio::spawn(run_task(
        Arc::clone(shared),
        guard,
        sql.to_owned(),
        params,
        token,
        run,
        tx,
    ));
    Ok(stream::unfold(rx, |mut rx| async move {
        rx.recv().await.map(|item| (item, rx))
    })
    .boxed())
}

async fn run_task(
    shared: Arc<Shared>,
    mut guard: OwnedMutexGuard<Option<Conn>>,
    sql: String,
    params: Vec<MyValue>,
    token: CancellationToken,
    run: u64,
    tx: Sender,
) {
    let finished = match guard.as_mut() {
        Some(conn) => AssertUnwindSafe(run_statement(conn, &shared, &sql, params, &token, &tx))
            .catch_unwind()
            .await
            .unwrap_or_else(|_| {
                tracing::error!(
                    connection_id = shared.connection_id,
                    "the MySQL statement task panicked; closing the session"
                );
                Finished {
                    tail: vec![Err(Error::internal(
                        "the statement task panicked; the session was closed",
                    ))],
                    close_session: true,
                }
            }),
        None => Finished::items(vec![Err(closed())]),
    };
    if finished.close_session
        && let Some(conn) = guard.take()
    {
        abandon(&shared, conn);
    }
    shared.end_run(run);
    // Release the session before the last items, so a consumer that sees the end of the stream
    // can run the next statement right away.
    drop(guard);
    for item in finished.tail {
        if tx.send(item).await.is_err() {
            break;
        }
    }
}

/// How a run ended: the items to send after the session is released, and whether the session
/// must be closed.
struct Finished {
    tail: Vec<Result<ResultItem>>,
    close_session: bool,
}

impl Finished {
    fn items(tail: Vec<Result<ResultItem>>) -> Self {
        Self {
            tail,
            close_session: false,
        }
    }
}

/// What the cancel watcher did.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Watched {
    /// No cancel request, or the statement ended before any `KILL` was attempted.
    Quiet,
    /// At least one `KILL QUERY` was attempted and every one of them is settled.
    Killed,
    /// The statement did not stop by the deadline, or a `KILL` may still arrive: close the
    /// session.
    Abandon,
}

/// What a fully read statement left behind.
#[derive(Debug, Default)]
struct Summary {
    /// Warning count of the last statement (details come from `SHOW WARNINGS`).
    last_warnings: u16,
}

/// Sends items to the consumer unless the run was cancelled.
struct Sink<'a> {
    tx: &'a Sender,
    stop: &'a AtomicBool,
}

impl Sink<'_> {
    fn stopped(&self) -> bool {
        self.stop.load(Ordering::SeqCst)
    }

    async fn emit(&self, item: ResultItem) {
        if self.stopped() {
            return;
        }
        if self.tx.send(Ok(item)).await.is_err() {
            // The consumer dropped the stream: treat it as a cancel (the watcher kills).
            self.stop.store(true, Ordering::SeqCst);
        }
    }
}

/// Runs one statement (or script) with the watcher; returns the items to send after the session
/// is released.
async fn run_statement(
    conn: &mut Conn,
    shared: &Shared,
    sql: &str,
    params: Vec<MyValue>,
    token: &CancellationToken,
    tx: &Sender,
) -> Finished {
    if let Err(e) = shared.rollback_if_needed(conn).await {
        return Finished::items(vec![Err(e)]);
    }
    let stop = AtomicBool::new(false);
    let done = CancellationToken::new();
    let (result, watched) = {
        let sink = Sink { tx, stop: &stop };
        let work = async {
            let result = drive(&mut *conn, sql, params, &sink, shared).await;
            done.cancel();
            result
        };
        let watcher = watch(shared, token, tx, &done, &stop);
        tokio::pin!(work, watcher);
        tokio::select! {
            biased;
            result = &mut work => (Some(result), watcher.await),
            watched = &mut watcher => match watched {
                // Dropping `work` drops the half-read result; the session is closed below.
                Watched::Abandon => (None, watched),
                Watched::Quiet | Watched::Killed => (Some(work.await), watched),
            },
        }
    };
    let result = match (result, watched) {
        (_, Watched::Abandon) | (None, _) => {
            return Finished {
                tail: vec![Err(Error::Cancelled)],
                close_session: true,
            };
        }
        (Some(result), Watched::Killed) => {
            settle(conn).await;
            result
        }
        (Some(result), Watched::Quiet) => result,
    };
    if stop.load(Ordering::SeqCst) {
        return Finished::items(vec![Err(Error::Cancelled)]);
    }
    Finished::items(match result {
        Ok(summary) if summary.last_warnings > 0 => match show_warnings(conn).await {
            Ok(notices) => notices
                .into_iter()
                .map(|n| Ok(ResultItem::Notice(n)))
                .collect(),
            Err(e) => vec![Ok(ResultItem::Notice(Notice::warning(format!(
                "the statement produced {} warning(s), but SHOW WARNINGS failed: {e}",
                summary.last_warnings
            ))))],
        },
        Ok(_) => Vec::new(),
        Err(e) => vec![Err(e)],
    })
}

/// Waits for a cancel request or a dropped stream, then kills the running statement until the
/// reader is done or [`CANCEL_DEADLINE`] passes (see [`Watched`]).
async fn watch(
    shared: &Shared,
    token: &CancellationToken,
    tx: &Sender,
    done: &CancellationToken,
    stop: &AtomicBool,
) -> Watched {
    tokio::select! {
        biased;
        () = done.cancelled() => return Watched::Quiet,
        () = token.cancelled() => {}
        () = tx.closed() => {}
    }
    stop.store(true, Ordering::SeqCst);
    let deadline = Instant::now() + CANCEL_DEADLINE;
    let mut attempted = false;
    loop {
        if done.is_cancelled() {
            return if attempted {
                Watched::Killed
            } else {
                Watched::Quiet
            };
        }
        let budget = deadline.saturating_duration_since(Instant::now());
        if budget.is_zero() {
            tracing::warn!(
                connection_id = shared.connection_id,
                "the cancelled statement did not stop in time; closing the session"
            );
            return Watched::Abandon;
        }
        attempted = true;
        match kill_query(shared, deadline).await {
            KillResult::Settled => {}
            KillResult::Failed(e) => tracing::warn!(
                connection_id = shared.connection_id,
                error = %e,
                "KILL QUERY failed"
            ),
            KillResult::Unknown(e) => {
                tracing::warn!(
                    connection_id = shared.connection_id,
                    error = %e,
                    "KILL QUERY got no reply and could still arrive; closing the session"
                );
                return Watched::Abandon;
            }
        }
        tokio::select! {
            () = done.cancelled() => {}
            () = tokio::time::sleep(KILL_RETRY) => {}
        }
    }
}

/// Outcome of one `KILL QUERY` attempt.
enum KillResult {
    /// The server processed it (or the target no longer exists).
    Settled,
    /// It was not sent, or the server refused it: it cannot take effect later.
    Failed(Error),
    /// It may have been sent but no reply came: it could still reach a later statement.
    Unknown(Error),
}

/// Sends `KILL QUERY <id>` over a new connection with the session's options, within `deadline`
/// (the reply always gets at least [`KILL_REPLY_MIN`]).
async fn kill_query(shared: &Shared, deadline: Instant) -> KillResult {
    let budget = deadline.saturating_duration_since(Instant::now());
    let mut side = match tokio::time::timeout(
        KILL_CONNECT_TIMEOUT.min(budget),
        Conn::new(shared.side_opts.clone()),
    )
    .await
    {
        Ok(Ok(conn)) => conn,
        Ok(Err(e)) => return KillResult::Failed(map_error(e)),
        Err(_) => return KillResult::Failed(Error::timeout("opening the cancel connection")),
    };
    let wait = KILL_REPLY_TIMEOUT
        .min(deadline.saturating_duration_since(Instant::now()))
        .max(KILL_REPLY_MIN);
    let sql = format!("KILL QUERY {}", shared.connection_id);
    let outcome = match tokio::time::timeout(wait, side.query_drop(sql)).await {
        Ok(Ok(())) => KillResult::Settled,
        Ok(Err(e)) if is_server_error(&e, ER_NO_SUCH_THREAD) => KillResult::Settled,
        // Any other server reply also means the KILL was handled.
        Ok(Err(e @ mysql_async::Error::Server(_))) => KillResult::Failed(map_error(e)),
        Ok(Err(e)) => KillResult::Unknown(map_error(e)),
        Err(_) => KillResult::Unknown(Error::timeout("waiting for the KILL QUERY reply")),
    };
    // Closing may wait for a reply that never comes: do it in the background, bounded.
    tokio::spawn(async move {
        match tokio::time::timeout(ABANDON_CLOSE_GRACE, side.disconnect()).await {
            Ok(Ok(())) | Err(_) => {}
            Ok(Err(e)) => tracing::debug!(error = %e, "closing the cancel connection failed"),
        }
    });
    outcome
}

/// Closes a session whose statement could not be stopped (or that a late `KILL` could still
/// reach), then asks the server to end it with `KILL CONNECTION`, both in the background.
fn abandon(shared: &Shared, conn: Conn) {
    let side_opts = shared.side_opts.clone();
    let id = shared.connection_id;
    tokio::spawn(async move {
        // `disconnect` marks the session closed, then waits for the pending result; dropping it
        // at the deadline closes the socket.
        if let Ok(Err(e)) = tokio::time::timeout(ABANDON_CLOSE_GRACE, conn.disconnect()).await {
            tracing::debug!(error = %e, "closing the abandoned MySQL session failed");
        }
        match tokio::time::timeout(ABANDON_KILL_TIMEOUT, kill_connection(side_opts, id)).await {
            Ok(Ok(())) => {}
            Ok(Err(e)) if is_server_error(&e, ER_NO_SUCH_THREAD) => {}
            Ok(Err(e)) => tracing::warn!(
                connection_id = id,
                error = %e,
                "KILL CONNECTION of an abandoned session failed"
            ),
            Err(_) => tracing::warn!(
                connection_id = id,
                "KILL CONNECTION of an abandoned session timed out"
            ),
        }
    });
}

/// Sends `KILL CONNECTION <id>` over a new connection.
async fn kill_connection(opts: Opts, id: u32) -> std::result::Result<(), mysql_async::Error> {
    let mut side = Conn::new(opts).await?;
    let result = side.query_drop(format!("KILL CONNECTION {id}")).await;
    if let Err(e) = side.disconnect().await {
        tracing::debug!(error = %e, "closing the cancel connection failed");
    }
    result
}

/// Absorbs a `KILL QUERY` that reached the server after the statement ended.
async fn settle(conn: &mut Conn) {
    match conn.query_drop("DO 0").await {
        Ok(()) => {}
        Err(e) if is_server_error(&e, ER_QUERY_INTERRUPTED) => {}
        Err(e) => tracing::debug!(error = %e, "post-cancel DO 0 failed"),
    }
}

/// Reads every result set of the statement, emitting items through `sink`.
async fn drive(
    conn: &mut Conn,
    sql: &str,
    params: Vec<MyValue>,
    sink: &Sink<'_>,
    shared: &Shared,
) -> Result<Summary> {
    if params.is_empty() {
        let result = conn.query_iter(sql).await.map_err(map_error)?;
        consume(result, sink, shared).await
    } else {
        let result = conn
            .exec_iter(sql, Params::Positional(params))
            .await
            .map_err(map_error)?;
        consume(result, sink, shared).await
    }
}

async fn consume<P: Protocol>(
    mut result: QueryResult<'_, 'static, P>,
    sink: &Sink<'_>,
    shared: &Shared,
) -> Result<Summary> {
    let options = &shared.options;
    let mut summary = Summary::default();
    let mut statement = 0usize;
    loop {
        // `None`: no more result sets, or the next one failed; `next` reports the failure.
        let Some(columns) = result.columns() else {
            result.next().await.map_err(map_error)?;
            break;
        };
        statement += 1;
        let warnings;
        if columns.is_empty() {
            warnings = result.warnings();
            sink.emit(ResultItem::RowsAffected(result.affected_rows()))
                .await;
            if let Some(id) = result.last_insert_id().filter(|id| *id != 0) {
                shared.last_insert_id.store(id, Ordering::Relaxed);
                sink.emit(ResultItem::Notice(Notice {
                    severity: NoticeSeverity::Info,
                    message: format!("last insert id: {id}"),
                    code: Some(LAST_INSERT_ID_CODE.to_owned()),
                }))
                .await;
            }
            // Consumes the OK result and moves to the next result set.
            result.next().await.map_err(map_error)?;
        } else {
            let shape = ResultShape::new(&columns, options.types);
            sink.emit(ResultItem::Schema(shape.schema.clone())).await;
            let mut batch = BatchBuilder::new(&shape);
            // `next` returns `None` at the end of this set, after reading the next set's header.
            while let Some(row) = result.next().await.map_err(map_error)? {
                if sink.stopped() {
                    continue; // drain without decoding
                }
                batch.push(row.unwrap_raw());
                if batch.rows() >= options.batch_rows || batch.bytes() >= options.batch_bytes {
                    sink.emit(ResultItem::Batch(batch.finish()?)).await;
                }
            }
            if batch.rows() > 0 && !sink.stopped() {
                sink.emit(ResultItem::Batch(batch.finish()?)).await;
            }
            let lossy = batch.take_lossy();
            if !lossy.is_empty() {
                let detail: Vec<String> = lossy.iter().map(|(c, n)| format!("{c} ({n})")).collect();
                sink.emit(ResultItem::Notice(Notice::warning(format!(
                    "some values could not be represented exactly (for example zero dates) and \
                     are shown as NULL or with replacement characters: {}",
                    detail.join(", ")
                ))))
                .await;
            }
            // The terminator's warning count is still current unless the next result set is an
            // OK packet, which has already replaced it (its count is then unknown).
            warnings = match result.columns() {
                Some(next) if next.is_empty() => 0,
                _ => result.warnings(),
            };
        }
        if result.columns().is_some() {
            if warnings > 0 {
                sink.emit(ResultItem::Notice(Notice {
                    severity: NoticeSeverity::Warning,
                    message: format!(
                        "statement {statement} produced {warnings} warning(s); SHOW WARNINGS \
                         only reports the last statement of a script"
                    ),
                    code: None,
                }))
                .await;
            }
        } else {
            summary.last_warnings = warnings;
        }
    }
    Ok(summary)
}

/// Reads `SHOW WARNINGS` (`Level`, `Code`, `Message`) as notices. Columns are read leniently
/// (never with a panicking conversion).
async fn show_warnings(conn: &mut Conn) -> Result<Vec<Notice>> {
    let rows: Vec<Row> = conn.query("SHOW WARNINGS").await.map_err(map_error)?;
    Ok(rows
        .iter()
        .map(|row| warning_notice([row.as_ref(0), row.as_ref(1), row.as_ref(2)]))
        .collect())
}

/// One `SHOW WARNINGS` row (`Level`, `Code`, `Message`; missing cells are empty) as a notice.
fn warning_notice(cells: [Option<&MyValue>; 3]) -> Notice {
    let [level, code, message] = cells.map(|c| c.map(value_text).unwrap_or_default());
    Notice {
        severity: if level.eq_ignore_ascii_case("note") {
            NoticeSeverity::Info
        } else {
            NoticeSeverity::Warning
        },
        message,
        code: (!code.is_empty()).then_some(code),
    }
}

/// A `SHOW WARNINGS` cell as text.
fn value_text(v: &MyValue) -> String {
    match v {
        MyValue::Bytes(b) => String::from_utf8_lossy(b).into_owned(),
        MyValue::Int(i) => i.to_string(),
        MyValue::UInt(u) => u.to_string(),
        _ => String::new(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn warning_rows_never_panic() {
        let level = MyValue::Bytes(b"Warning".to_vec());
        let code = MyValue::UInt(1292);
        // Not valid UTF-8: a `(String, String, String)` conversion would panic here.
        let message = MyValue::Bytes(b"Truncated \xff value".to_vec());
        let n = warning_notice([Some(&level), Some(&code), Some(&message)]);
        assert_eq!(n.severity, NoticeSeverity::Warning);
        assert_eq!(n.code.as_deref(), Some("1292"));
        assert!(n.message.starts_with("Truncated"), "{}", n.message);

        let note = MyValue::Bytes(b"Note".to_vec());
        let n = warning_notice([Some(&note), Some(&MyValue::NULL), None]);
        assert_eq!(n.severity, NoticeSeverity::Info);
        assert_eq!(n.code, None);
        assert_eq!(n.message, "");
        assert_eq!(value_text(&MyValue::Int(-3)), "-3");
    }
}
