//! An open MySQL / MariaDB session: streaming execution, cancellation and transactions.
//!
//! # Execution model
//!
//! `mysql_async`'s result readers borrow the session, but a [`ResultStream`] must be `'static`.
//! So [`MySqlConnection::execute`] takes the session lock (an owned `tokio` mutex guard) and moves
//! it into a spawned task, which reads rows and sends [`ResultItem`]s through a small bounded
//! channel. The channel is the back-pressure: when the consumer stops reading, the task stops
//! reading from the socket and the server blocks on its send. Nothing is buffered beyond one
//! batch per channel slot.
//!
//! # Cancellation
//!
//! A watcher runs next to the reader. When the run's token is cancelled (directly or through
//! [`MySqlConnection::cancel_running`]) or the consumer drops the stream, it marks the run as
//! cancelled and sends `KILL QUERY <connection id>` over a short-lived second connection that
//! uses the same [`mysql_async::Opts`] as the session (same dial address, credentials and TLS),
//! repeating it every [`KILL_RETRY`] while the run is still reading (a killed `SLEEP` returns a
//! normal row, so the next statement of a script would otherwise start). The reader never drops a
//! half-read packet: it keeps reading until the server finishes, which keeps the session usable.
//!
//! Every `KILL` is sent, and its reply awaited, while the run still holds the session lock, so it
//! cannot reach a later statement of this connection. After a kill the session runs `DO 0` to
//! absorb a kill flag that arrived just as the statement ended. The stream then yields one
//! `Err(Error::Cancelled)` and ends.
//!
//! The kills are bounded by [`CANCEL_DEADLINE`]. When the statement is still running at the
//! deadline (the side connection cannot be opened, the server ignores the kill, a script keeps
//! starting new statements), or when a `KILL` was sent but its reply never came (it could still
//! reach a later statement), the run **abandons the session**: it drops the half-read result,
//! closes the session (later calls fail with "the connection is closed"), sends
//! `KILL CONNECTION` in the background, and still yields `Err(Error::Cancelled)`.
//!
//! A panic while running a statement is caught: the session is closed and the stream yields
//! `Error::Internal` instead of ending as if the statement had succeeded.

