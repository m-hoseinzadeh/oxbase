//! MySQL and MariaDB language data for code insight (M6, `docs/m6-contracts.md` §4.4): keywords
//! and reserved words of the MySQL 8 keyword list (with the words MariaDB also reserves), the
//! built-in string, numeric, date and time, aggregate, window, JSON, flow control, conversion,
//! encryption and information functions, and the data types. Written for Oxbase from the MySQL
//! and MariaDB documentation; summaries are our own. Both engines share the keywords, functions
//! and types; each has its own reserved words (MySQL 8's list reserves words MariaDB accepts as
//! names, such as `GROUPS` and `RANK`).

use oxbase_dialect::{FunctionInfo, FunctionKind, SqlLanguage, TypeInfo, TypeParams};
use oxbase_types::Engine;

use FunctionKind::{Aggregate as A, Scalar as S, Window as W};
use TypeParams::{Length as L, None as N, Precision as P, PrecisionScale as PS};

/// The MySQL language data (registered by [`super::register`]).
pub const LANGUAGE: SqlLanguage = SqlLanguage {
    engine: Some(Engine::MySql),
    keywords: KEYWORDS,
    reserved: RESERVED,
    functions: FUNCTIONS,
    types: TYPES,
    ident_chars: "$",
    default_schema: None,
};

/// The MariaDB language data: the MySQL keywords, functions and types under MariaDB's engine,
/// with MariaDB's own reserved words.
pub const MARIADB_LANGUAGE: SqlLanguage = SqlLanguage {
    engine: Some(Engine::MariaDb),
    keywords: KEYWORDS,
    reserved: MARIADB_RESERVED,
    functions: FUNCTIONS,
    types: TYPES,
    ident_chars: "$",
    default_schema: None,
};

/// One function overload available on every supported version.
const fn f(
    name: &'static str,
    args: &'static str,
    returns: &'static str,
    kind: FunctionKind,
    min_args: u8,
    max_args: Option<u8>,
    summary: &'static str,
) -> FunctionInfo {
    FunctionInfo {
        name,
        args,
        returns,
        kind,
        min_args,
        max_args,
        summary,
        since: None,
    }
}

/// One data type.
const fn ty(name: &'static str, params: TypeParams, summary: &'static str) -> TypeInfo {
    TypeInfo {
        name,
        params,
        summary,
    }
}

