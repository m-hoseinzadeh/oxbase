#[cfg(test)]
mod tests {
    use oxbase_dialect::DialectRegistry;

    use super::*;

    #[test]
    fn the_data_is_well_formed_and_registered() {
        assert_eq!(LANGUAGE.validate(), Vec::<String>::new());
        assert!(
            LANGUAGE.functions.len() >= 200,
            "{}",
            LANGUAGE.functions.len()
        );
        assert!(LANGUAGE.is_reserved("select"));
        assert!(LANGUAGE.is_reserved("Interval"));
        assert!(LANGUAGE.is_keyword("engine"));
        assert!(!LANGUAGE.is_reserved("engine"));
        assert_eq!(LANGUAGE.function("json_extract").len(), 1);
        assert!(LANGUAGE.type_info("varchar").is_some());
        assert_eq!(MARIADB_LANGUAGE.engine, Some(Engine::MariaDb));
        assert_eq!(MARIADB_LANGUAGE.validate(), Vec::<String>::new());
        assert_eq!(MARIADB_LANGUAGE.functions, LANGUAGE.functions);
        // MySQL 8 reserves these; MariaDB accepts them as names.
        for word in [
            "groups", "rank", "system", "lateral", "lag", "lead", "empty",
        ] {
            assert!(LANGUAGE.is_reserved(word), "{word}");
            assert!(!MARIADB_LANGUAGE.is_reserved(word), "{word}");
            assert!(MARIADB_LANGUAGE.is_keyword(word), "{word}");
        }
        assert!(MARIADB_LANGUAGE.is_reserved("returning"));
        assert!(MARIADB_LANGUAGE.is_reserved("page_checksum"));
        let mut reg = DialectRegistry::new();
        super::super::register(&mut reg);
        for engine in [Engine::MySql, Engine::MariaDb] {
            assert!(reg.has_language(engine));
            assert_eq!(reg.language(engine).engine, Some(engine));
            let problems: Vec<String> = reg
                .missing_insight_roles(engine)
                .into_iter()
                .filter(|p| p.contains("SqlLanguage"))
                .collect();
            assert_eq!(problems, Vec::<String>::new());
        }
    }
}
