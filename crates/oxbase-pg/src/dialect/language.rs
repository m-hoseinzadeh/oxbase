#[cfg(test)]
mod tests {
    use oxbase_dialect::DialectRegistry;

    use super::*;

    #[test]
    fn the_data_is_well_formed_and_registered() {
        assert_eq!(LANGUAGE.validate(), Vec::<String>::new());
        assert!(
            LANGUAGE.functions.len() >= 250,
            "{}",
            LANGUAGE.functions.len()
        );
        assert!(LANGUAGE.is_reserved("select"));
        assert!(LANGUAGE.is_reserved("ilike"));
        assert!(LANGUAGE.is_keyword("materialized"));
        assert!(!LANGUAGE.is_reserved("name"));
        assert_eq!(LANGUAGE.function("jsonb_set").len(), 1);
        assert_eq!(LANGUAGE.function("log").len(), 2);
        assert!(LANGUAGE.type_info("timestamp with time zone").is_some());
        let mut reg = DialectRegistry::new();
        super::super::register(&mut reg);
        assert!(reg.has_language(Engine::Postgres));
        let problems: Vec<String> = reg
            .missing_insight_roles(Engine::Postgres)
            .into_iter()
            .filter(|p| p.contains("SqlLanguage"))
            .collect();
        assert_eq!(problems, Vec::<String>::new());
    }
}
