//! PostgreSQL language data for code insight (M6, `docs/m6-contracts.md` §4.4): the keywords
//! PostgreSQL recognises (its column of the SQL key words appendix; reserved = "reserved" and
//! "reserved, can be function or type"), the built-in mathematical, string, date and time,
//! aggregate, window, JSON, array, conditional, formatting, set-returning and system information
//! functions, and the built-in data types with their common aliases. Written for Oxbase from the
//! PostgreSQL documentation; summaries are our own. Functions added after PostgreSQL 12 carry the
//! release that introduced them (`since`).

use oxbase_dialect::{FunctionInfo, FunctionKind, SqlLanguage, TypeInfo, TypeParams};
use oxbase_types::Engine;

use FunctionKind::{Aggregate as A, Scalar as S, Table as T, Window as W};
use TypeParams::{Length as L, None as N, Precision as P, PrecisionScale as PS};

/// The PostgreSQL language data (registered by [`super::register`]).
pub const LANGUAGE: SqlLanguage = SqlLanguage {
    engine: Some(Engine::Postgres),
    keywords: KEYWORDS,
    reserved: RESERVED,
    functions: FUNCTIONS,
    types: TYPES,
    ident_chars: "$",
    default_schema: Some("public"),
};

/// One function overload available on every supported version.
const fn f(
    name: &'static str,
    args: &'static str,
    returns: &'static str,
    kind: FunctionKind,
    min_args: u8,
    max_args: Option<u8>,
    summary: &'static str,
) -> FunctionInfo {
    FunctionInfo {
        name,
        args,
        returns,
        kind,
        min_args,
        max_args,
        summary,
        since: None,
    }
}

/// One function overload that needs server version `since` (major, minor) or later.
const fn fs(base: FunctionInfo, since: (u32, u32)) -> FunctionInfo {
    FunctionInfo {
        since: Some(since),
        ..base
    }
}

/// One data type.
const fn ty(name: &'static str, params: TypeParams, summary: &'static str) -> TypeInfo {
    TypeInfo {
        name,
        params,
        summary,
    }
}

