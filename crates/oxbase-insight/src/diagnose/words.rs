#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_upper_case() {
        for list in [
            ALIAS_STOP,
            BODY_LEAD,
            CLAUSE_AFTER_COMMA,
            CONTROL,
            CREATE_MODS,
            CREATE_OBJECTS,
            DML_CONT_PREV,
            DML_MODS,
            EXPR_WORDS,
            FOR_CLAUSE,
            HIDDEN_COLUMNS,
            JOIN_MODS,
            PSEUDO_TABLES,
            ROUTINES,
            SELECT_CONT_PREV,
            SELECT_MODS,
            STATEMENT_STARTS,
            SYNTAX_ARG_WORDS,
            SYSTEM_SCHEMAS,
            TSQL_SPLIT,
            TYPE_ARG_FUNCS,
            VALUE_WORDS,
        ] {
            for pair in list.windows(2) {
                assert!(pair[0] < pair[1], "{pair:?}");
            }
            for w in list {
                assert_eq!(w.to_ascii_uppercase(), *w);
            }
        }
        assert!(has(EXPR_WORDS, "INTERVAL"));
        assert!(!has(EXPR_WORDS, "interval"));
        assert!(system_like("pg_class"));
        assert!(system_like("INFORMATION_SCHEMA"));
        assert!(!system_like("orders"));
    }
}
