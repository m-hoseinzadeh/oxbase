//! Word lists the diagnostics parser reads (upper case, sorted by byte order, so [`has`] can
//! binary-search them). They describe SQL syntax shared by the dialects (clause words, words
//! that are never column names in an expression, functions whose arguments hold syntax
//! words); per-engine keywords, functions and types come from `SqlLanguage`.

/// `true` when `upper` (an upper-case word) is in `list`.
pub(crate) fn has(list: &[&str], upper: &str) -> bool {
    list.binary_search(&upper).is_ok()
}

/// `true` when `name` looks like a system object the cache may not hold (`pg_class`,
/// `sqlite_master`, `sys.objects`, `information_schema`).
pub(crate) fn system_like(name: &str) -> bool {
    let lower = name.to_ascii_lowercase();
    has(SYSTEM_SCHEMAS, &name.to_ascii_uppercase())
        || [
            "pg_",
            "sqlite_",
            "sys",
            "information_schema",
            "dm_",
            "performance_schema",
        ]
        .iter()
        .any(|p| lower.starts_with(p))
}

