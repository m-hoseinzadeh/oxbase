-- M8 seed (PostgreSQL): the structure / data sync pair, the restore target and the transfer
-- source set of tests/fixtures.toml [m8] / [m8.postgres] (docs/m8-contracts.md section 9).
-- Runs once, as POSTGRES_USER (oxbase) in POSTGRES_DB (oxbase_test), on an empty data volume.
-- Re-runnable: every schema is dropped and created again.
--
--   m8_src      SOURCE of the pair (the desired state)
--   m8_tgt      TARGET of the pair (what a sync must change)
--   m8_restore  empty; restores land here
--   m8_xfer     the transfer source set (m8_types, m8_parent, m8_child, m8_tree)
--
-- The conformance harness (crates/oxbase-conformance/src/m8) builds fresh copies of the
-- sections between the `-- m8:<name> begin` / `-- m8:<name> end` markers in scratch schemas
-- (`m8_t_<token>_...`): it replaces the whole words m8_src, m8_tgt and m8_xfer and runs the
-- statements in order. So inside a section every object name is schema-qualified, and the
-- schema names appear only as those words. The file is ASCII only: non-ASCII values are built
-- with U& escapes.

DROP SCHEMA IF EXISTS m8_restore CASCADE;
CREATE SCHEMA m8_restore;
COMMENT ON SCHEMA m8_restore IS 'M8 restore target (tests empty it first)';

-- m8:pair begin
DROP SCHEMA IF EXISTS m8_src CASCADE;
DROP SCHEMA IF EXISTS m8_tgt CASCADE;
CREATE SCHEMA m8_src;
