SELECT i,
       CASE i WHEN 1 THEN U&'gr\00FC\00DFe' WHEN 2 THEN U&'\65E5\672C' WHEN 4 THEN U&'\+01F600'
              ELSE 'name-' || i END,
       CASE i WHEN 1 THEN 1234567890123456789012345678.0123456789
              WHEN 2 THEN -1234567890123456789012345678.0123456789
              WHEN 6 THEN -0.5
              ELSE i * 1.25 END,
       CASE i % 3 WHEN 1 THEN '\x00ff10'::bytea WHEN 2 THEN NULL ELSE '\x0a0b'::bytea END,
       timestamptz '2026-01-01 10:00:00+05:30' + (i - 1) * interval '1 day',
       CASE i WHEN 9 THEN NULL WHEN 10 THEN 'y' ELSE 'note ' || i END
FROM generate_series(1, 20) AS g (i);
-- Values that need quoting in a script: a quote, a backslash, `;` and `--` (id 3 differs,
-- so its UPDATE writes this name) and a quote, double quotes and N'...' (id 19 is inserted).
