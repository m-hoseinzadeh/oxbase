CREATE VIEW m8_src.active_customers AS
SELECT id, name, email FROM m8_src.customers WHERE phone IS NOT NULL;

CREATE SEQUENCE m8_src.invoice_seq START 1000 INCREMENT 1;

CREATE FUNCTION m8_src.order_total(p_order integer) RETURNS numeric
    LANGUAGE sql STABLE
    AS $$SELECT coalesce(sum(qty * unit_price), 0) FROM m8_src.order_items WHERE order_id = p_order$$;

CREATE FUNCTION m8_src.orders_audit_fn() RETURNS trigger
    LANGUAGE plpgsql
    AS $$
BEGIN
    INSERT INTO m8_src.order_audit (order_id, action) VALUES (NEW.id, 'insert');
    RETURN NULL;
END
$$;

CREATE TRIGGER orders_audit AFTER INSERT ON m8_src.orders
    FOR EACH ROW EXECUTE FUNCTION m8_src.orders_audit_fn();

