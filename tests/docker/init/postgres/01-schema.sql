-- oxbase_test fixture schema (PostgreSQL). Keep in step with the other engines' init scripts:
-- customers, orders (FK), idx_orders_customer_id, v_customer_order_totals, order_no_seq,
-- identity columns and trg_customers_updated_at.
-- Runs once, as POSTGRES_USER (oxbase) in POSTGRES_DB (oxbase_test), on an empty data volume.

CREATE SEQUENCE order_no_seq AS integer START WITH 1000 INCREMENT BY 1;

CREATE TABLE customers (
    id          integer GENERATED BY DEFAULT AS IDENTITY,
    email       varchar(255) NOT NULL,
    name        varchar(100) NOT NULL,
    created_at  timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  timestamp    NULL,
    CONSTRAINT pk_customers PRIMARY KEY (id),
    CONSTRAINT uq_customers_email UNIQUE (email)
);

CREATE TABLE orders (
    id           integer GENERATED BY DEFAULT AS IDENTITY,
    order_no     integer       NOT NULL DEFAULT nextval('order_no_seq'),
    customer_id  integer       NOT NULL,
    status       varchar(20)   NOT NULL DEFAULT 'new',
    total        numeric(12,2) NOT NULL DEFAULT 0,
    ordered_at   timestamp     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_orders PRIMARY KEY (id),
    CONSTRAINT uq_orders_order_no UNIQUE (order_no),
    CONSTRAINT fk_orders_customer FOREIGN KEY (customer_id)
        REFERENCES customers (id) ON DELETE CASCADE,
    CONSTRAINT ck_orders_total_nonneg CHECK (total >= 0)
);

ALTER SEQUENCE order_no_seq OWNED BY orders.order_no;

CREATE INDEX idx_orders_customer_id ON orders (customer_id);

CREATE VIEW v_customer_order_totals AS
SELECT c.id                     AS customer_id,
       c.name                   AS name,
       COUNT(o.id)              AS order_count,
       COALESCE(SUM(o.total), 0) AS total_spent
FROM customers c
LEFT JOIN orders o ON o.customer_id = c.id
GROUP BY c.id, c.name;

CREATE FUNCTION fn_customers_set_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_customers_updated_at
    BEFORE UPDATE ON customers
    FOR EACH ROW EXECUTE FUNCTION fn_customers_set_updated_at();
