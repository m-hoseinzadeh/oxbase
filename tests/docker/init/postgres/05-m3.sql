-- M3 seed objects for grid editing (PostgreSQL). Names and shapes come from tests/fixtures.toml
-- ([m3] and [m3.postgres]): editable seed tables m3_edit_pk / m3_edit_uq, the read-only
-- m3_edit_nokey and m3_edit_view, all in schema m3. Round-trip scratch tables
-- (m3_rt_<kind>_<token>) are created and dropped by the tests in the same schema.
-- Runs once, as POSTGRES_USER (oxbase) in POSTGRES_DB (oxbase_test), on an empty data volume.
-- The entrypoint starts each init file on POSTGRES_DB, so this file runs there although
-- 04-m2.sql ends connected to another database.
-- Live edit tests never change seed rows 1-3: they insert their own rows and delete them.

CREATE SCHEMA m3;
COMMENT ON SCHEMA m3 IS 'M3 grid editing seeds and designer round-trip scratch tables';

CREATE TABLE m3.m3_edit_pk (
    id      integer        GENERATED BY DEFAULT AS IDENTITY,
    code    varchar(20)    NOT NULL,
    name    text           NULL,
    amount  numeric(12,2)  NULL,
    flag    boolean        NULL,
    born    date           NULL,
    at      timestamp      NULL,
    doc     jsonb          NULL,
    data    bytea          NULL,
    total   numeric(14,2)  GENERATED ALWAYS AS (amount * 2) STORED,
    CONSTRAINT m3_edit_pk_pkey PRIMARY KEY (id),
    CONSTRAINT m3_edit_pk_code_key UNIQUE (code)
);

