/** Types an engine offers from a server version on (added to {@link TYPE_SUGGESTIONS}). */
const VERSIONED_TYPES: Partial<Record<Engine, ReadonlyArray<{ since: number; type: string }>>> = {
  mssql: [{ since: 17, type: "json" }],
};

/**
 * The type names offered for `engine` on a server of `version` (an unknown version, `0.0.0`,
 * counts as current).
 */
export function typeSuggestions(
  engine: Engine | undefined,
  version?: ServerVersion | undefined,
): string[] {
  if (!engine) return [];
  const base = [...(TYPE_SUGGESTIONS[engine] ?? [])];
  const major = version?.major ?? 0;
  for (const extra of VERSIONED_TYPES[engine] ?? []) {
    if (major === 0 || major >= extra.since) base.push(extra.type);
  }
  return base;
}

/**
 * What the designer offers per engine beyond `DesignerCapabilities` (docs/m4-contracts.md §7:
 * options the capabilities do not carry). Engines not listed use {@link COMMON_TRAITS}.
 */
export interface DesignTraits {
  /**
   * How identity columns are declared: `generated` (`GENERATED BY DEFAULT | ALWAYS`, a mode to
   * pick) or `seedIncrement` (`IDENTITY(seed, increment)`, always generated by the server).
   */
  identityStyle: "generated" | "seedIncrement";
  /** Identity can only be set on a new column (not added to, removed from or changed on one). */
  identityOnNewColumnsOnly: boolean;
  /** At most one identity column per table. */
  singleIdentity: boolean;
  /** Indexes and the primary key have a clustered / nonclustered choice (`clustered` extra). */
  clusteredIndexes: boolean;
  /** Indexes have included (non-key) columns (`include_columns` extra). */
  includedColumns: boolean;
  /** The word for a stored generated column. */
  storedLabel: string;
  /** Index kinds (`index_kind` extra) the designer edits; other kinds are kept as they are. */
  editableIndexKinds: readonly string[] | null;
}

const COMMON_TRAITS: DesignTraits = {
  identityStyle: "generated",
  identityOnNewColumnsOnly: false,
  singleIdentity: false,
  clusteredIndexes: false,
  includedColumns: false,
  storedLabel: "Stored",
  editableIndexKinds: null,
};

const DESIGN_TRAITS: Partial<Record<Engine, Partial<DesignTraits>>> = {
  mssql: {
    identityStyle: "seedIncrement",
    identityOnNewColumnsOnly: true,
    singleIdentity: true,
    clusteredIndexes: true,
    includedColumns: true,
    storedLabel: "Persisted",
    editableIndexKinds: ["clustered", "nonclustered"],
  },
};

/** The designer traits of `engine`. */
export function designTraits(engine: Engine | undefined): DesignTraits {
  return { ...COMMON_TRAITS, ...(engine ? DESIGN_TRAITS[engine] : undefined) };
}

/** Extra ids (oxbase_types::props and the SQL Server extras of oxbase_mssql::extras). */
export const EXTRA = {
  clustered: "clustered",
  includeColumns: "include_columns",
  indexKind: "index_kind",
  rowVersion: "row_version",
  period: "period",
  temporalType: "temporal_type",
  memoryOptimized: "memory_optimized",
  tableType: "table_type",
} as const;

/** A boolean extra (`undefined` when absent or not a boolean). */
export function boolExtra(extras: Extras | undefined, id: string): boolean | undefined {
  const v = extras?.[id];
  return v?.type === "bool" ? v.value : undefined;
}

/** A text extra (`undefined` when absent or not text). */
export function textExtra(extras: Extras | undefined, id: string): string | undefined {
  const v = extras?.[id];
  return v?.type === "text" ? v.value : undefined;
}

/** A JSON-array-of-names extra (`include_columns`), empty when absent. */
export function namesExtra(extras: Extras | undefined, id: string): string[] {
  const v = extras?.[id];
  if (v?.type !== "json" || !Array.isArray(v.value)) return [];
  return v.value.filter((n): n is string => typeof n === "string");
}

/** `extras` with `id` set to `value`. */
export function withExtra(extras: Extras, id: string, value: Value): Extras {
  return { ...extras, [id]: value };
}

/**
 * Why an existing column's type cannot be changed in the designer, or `null`: the server
 * maintains `rowversion` and period columns, and they cannot be altered (drop and add instead).
 */
export function columnLockReason(column: ColumnDef): string | null {
  if (boolExtra(column.extras, EXTRA.rowVersion)) {
    return "The server maintains rowversion values: this column cannot be altered (drop it and add a new one).";
  }
  const period = textExtra(column.extras, EXTRA.period);
  if (period) {
    return `This is the ${period === "row_start" ? "start" : "end"} column of the table's system-time period: it cannot be altered here.`;
  }
  return null;
}

/**
 * Why an existing table is read-only in the designer, or `null`: system-versioned (temporal),
 * history, memory-optimized, graph and ledger tables (docs/m4-contracts.md §4.1).
 */
export function tableReadOnlyReason(design: TableDesign | null | undefined): string | null {
  const extras = design?.original?.extras;
  if (!extras) return null;
  const temporal = textExtra(extras, EXTRA.temporalType);
  if (temporal === "system_versioned") {
    return "This is a system-versioned (temporal) table: the designer cannot change it yet.";
  }
  if (temporal === "history") {
    return "This is the history table of a system-versioned table: the designer cannot change it.";
  }
  if (boolExtra(extras, EXTRA.memoryOptimized)) {
    return "This is a memory-optimized table: the designer cannot change it yet.";
  }
  const tableType = textExtra(extras, EXTRA.tableType);
  if (tableType === "graph_node" || tableType === "graph_edge") {
    return "This is a graph table: the designer cannot change it yet.";
  }
  if (tableType === "ledger") {
    return "This is a ledger table: the designer cannot change it.";
  }
  return null;
}

/** Why an index cannot be edited in the designer (an index kind it does not edit), or `null`. */
export function indexLockReason(index: IndexDef, traits: DesignTraits): string | null {
  const kind = textExtra(index.extras, EXTRA.indexKind);
  if (!kind || !traits.editableIndexKinds || traits.editableIndexKinds.includes(kind)) {
    return null;
  }
  return `A ${kind.replace(/_/g, " ")} index is kept as it is: the designer cannot change it.`;
}

/** Whether the table's primary key is clustered (an absent `clustered` extra means it is). */
export function primaryKeyClustered(design: TableDesign): boolean {
  if (!design.primaryKey || design.primaryKey.columns.length === 0) return false;
  return boolExtra(design.extras, EXTRA.clustered) ?? true;
}

/** Whether `index` is clustered (the `clustered` extra, or a clustered index kind). */
export function indexClustered(index: IndexDef): boolean {
  const flag = boolExtra(index.extras, EXTRA.clustered);
  if (flag !== undefined) return flag;
  return textExtra(index.extras, EXTRA.indexKind)?.startsWith("clustered") ?? false;
}

/**
 * What else holds the table's one clustered index, besides `self` (the primary key or the
 * index at that position): a name to show, or `null` when nothing else is clustered.
 */
export function otherClustered(design: TableDesign, self: "primaryKey" | number): string | null {
  if (self !== "primaryKey" && primaryKeyClustered(design)) return "the primary key";
  for (const [i, item] of design.indexes.entries()) {
    if (i !== self && indexClustered(item.def)) {
      return item.def.name ? `index ${item.def.name}` : `index ${i + 1}`;
    }
  }
  return null;
}

const WHOLE_NUMBER = /^[+-]?\d+$/;

/** Why `IDENTITY(seed, increment)` text is invalid, or `null`. */
export function identityProblem(seed: string, increment: string): string | null {
  if (!WHOLE_NUMBER.test(seed.trim())) return "The identity seed must be a whole number.";
  if (!WHOLE_NUMBER.test(increment.trim()) || /^[+-]?0+$/.test(increment.trim())) {
    return "The identity increment must be a whole number other than 0.";
  }
  return null;
}

/**
 * Why a column of type `native` cannot be an identity column, or `null`. SQL Server allows
 * tinyint, smallint, int, bigint and decimal/numeric with scale 0; a type the designer does
 * not know (an alias type) is left to the server.
 */
export function identityTypeProblem(native: string, engine: Engine | undefined): string | null {
  if (!native.trim()) return null;
  const t = guessDataType(native, engine);
  if (t.type === "int" || t.type === "other") return null;
  if (t.type === "decimal" && (t.scale ?? 0) === 0) return null;
  return "An identity column must be tinyint, smallint, int, bigint, or decimal/numeric with scale 0.";
}

/**
 * Problems the designer finds before asking the server: rules of the engine's designer traits
 * that a preview would only report as a failed apply. Errors block apply like the preview's.
 */
export function designProblems(design: TableDesign, engine: Engine | undefined): DesignIssue[] {
  const traits = designTraits(engine);
  const issues: DesignIssue[] = [];
  if (traits.identityStyle === "seedIncrement") {
    for (const [i, { column }] of design.columns.entries()) {
      if (!column.identity) continue;
      const path = `columns[${i}].identity`;
      const text =
        identityProblem(column.identity.start ?? "1", column.identity.increment ?? "1") ??
        identityTypeProblem(column.native_type, engine);
      if (text) issues.push({ severity: "error", path, message: text });
    }
  }
  if (traits.clusteredIndexes) {
    for (const [i, { def }] of design.indexes.entries()) {
      if (!indexClustered(def) || indexLockReason(def, traits)) continue;
      const path = `indexes[${i}]`;
      // Report a conflict once, on the later holder (the primary key comes first).
      const before = otherClustered({ ...design, indexes: design.indexes.slice(0, i + 1) }, i);
      if (before) {
        issues.push({
          severity: "error",
          path: `${path}.clustered`,
          message: `A table has at most one clustered index, and ${before} is already clustered.`,
        });
      }
      if (traits.includedColumns && namesExtra(def.extras, EXTRA.includeColumns).length > 0) {
        issues.push({
          severity: "error",
          path: `${path}.include_columns`,
          message: "A clustered index cannot have included columns.",
        });
      }
      if (def.predicate?.trim()) {
        issues.push({
          severity: "error",
          path: `${path}.predicate`,
          message: "A filtered index (with a WHERE condition) must be nonclustered.",
        });
      }
    }
  }
  return issues;
}

function args(text: string): number[] {
  const m = /\(([^)]*)\)/.exec(text);
  if (!m?.[1]) return [];
  return m[1]
    .split(",")
    .map((p) => Number.parseInt(p.trim(), 10))
    .filter((n) => Number.isFinite(n));
}

/**
 * The engine-neutral type of a type name as typed (`varchar(20)`, `bigint unsigned`). The
 * native text is what the engine runs; this only keeps the neutral type roughly in step.
 */
export function guessDataType(native: string, engine?: Engine): DataType {
  const t = native.trim().toLowerCase();
  const [a, b] = args(t);
  const unsigned = /\bunsigned\b/.test(t);
  const base = t
    .replace(/\(.*?\)/g, "")
    .replace(/\bunsigned\b|\bzerofill\b/g, "")
    .trim();
  if (engine === "mssql") {
    const tsql = guessTSqlType(base, t, a, b);
    if (tsql) return tsql;
  }
  if (base.endsWith("[]"))
    return { type: "array", element: guessDataType(native.trim().slice(0, -2), engine) };
  if (base === "tinyint" && a === 1) return { type: "bool" };
  if (["bool", "boolean"].includes(base)) return { type: "bool" };
  if (["tinyint", "int1"].includes(base)) return { type: "int", bits: 8, unsigned };
  if (["smallint", "int2", "smallserial"].includes(base))
    return { type: "int", bits: 16, unsigned };
  if (base === "mediumint") return { type: "int", bits: 32, unsigned };
  if (["int", "integer", "int4", "serial"].includes(base)) {
    // SQLite integers are 64-bit whatever they are called.
    return { type: "int", bits: engine === "sqlite" ? 64 : 32, unsigned };
  }
  if (["bigint", "int8", "bigserial"].includes(base)) return { type: "int", bits: 64, unsigned };
  if (["real", "float4"].includes(base)) return { type: "float", bits: 32 };
  if (["float", "double", "double precision", "float8"].includes(base)) {
    return { type: "float", bits: 64 };
  }
  if (["numeric", "decimal", "dec"].includes(base)) {
    return { type: "decimal", precision: a ?? null, scale: b ?? null };
  }
  if (["char", "character", "bpchar", "nchar"].includes(base)) {
    return { type: "char", length: a ?? null };
  }
  if (["varchar", "character varying", "nvarchar", "varchar2"].includes(base)) {
    return { type: "var_char", length: a ?? null };
  }
  if (/^(tiny|medium|long)?text$|^clob$|^citext$/.test(base)) return { type: "text" };
  if (["binary"].includes(base)) return { type: "binary", length: a ?? null };
  if (["varbinary"].includes(base)) return { type: "var_binary", length: a ?? null };
  if (/^(tiny|medium|long)?blob$|^bytea$/.test(base)) return { type: "var_binary", length: null };
  if (base === "date") return { type: "date" };
  if (["time", "time without time zone"].includes(base))
    return { type: "time", precision: a ?? null };
  if (["timestamptz", "timestamp with time zone"].includes(base)) {
    return { type: "timestamp_tz", precision: a ?? null };
  }
  if (["timestamp", "timestamp without time zone", "datetime"].includes(base)) {
    return { type: "timestamp", precision: a ?? null };
  }
  if (base === "interval") return { type: "interval" };
  if (base === "uuid") return { type: "uuid" };
  if (base === "json") return { type: "json", binary: false };
  if (base === "jsonb") return { type: "json", binary: true };
  return { type: "other", name: native.trim() };
}

/** SQL Server spellings (docs/m4-contracts.md §3.4); `null` for the shared rules. */
function guessTSqlType(
  base: string,
  text: string,
  a: number | undefined,
  b: number | undefined,
): DataType | null {
  const max = /\(\s*max\s*\)/.test(text);
  switch (base) {
    case "bit":
      return { type: "bool" };
    case "tinyint":
      return { type: "int", bits: 8, unsigned: true };
    case "float":
      return { type: "float", bits: a !== undefined && a <= 24 ? 32 : 64 };
    case "decimal":
    case "numeric":
      return { type: "decimal", precision: a ?? 18, scale: b ?? 0 };
    case "money":
      return { type: "decimal", precision: 19, scale: 4 };
    case "smallmoney":
      return { type: "decimal", precision: 10, scale: 4 };
    case "varchar":
    case "nvarchar":
      return max ? { type: "text" } : { type: "var_char", length: a ?? 1 };
    case "sysname":
      // A built-in alias of nvarchar(128) NOT NULL.
      return { type: "var_char", length: 128 };
    case "char":
    case "nchar":
      return { type: "char", length: a ?? 1 };
    case "ntext":
    case "text":
      return { type: "text" };
    case "varbinary":
      return { type: "var_binary", length: max ? null : (a ?? 1) };
    case "binary":
      return { type: "binary", length: a ?? 1 };
    case "image":
      return { type: "var_binary", length: null };
    case "time":
      return { type: "time", precision: a ?? 7 };
    case "datetime":
      return { type: "timestamp", precision: 3 };
    case "smalldatetime":
      return { type: "timestamp", precision: 0 };
    case "datetime2":
      return { type: "timestamp", precision: a ?? 7 };
    case "datetimeoffset":
      return { type: "timestamp_tz", precision: a ?? 7 };
    case "uniqueidentifier":
      return { type: "uuid" };
    case "json":
      return { type: "json", binary: true };
    case "rowversion":
    case "timestamp":
      return { type: "binary", length: 8 };
    case "xml":
    case "vector":
    case "sql_variant":
    case "hierarchyid":
    case "geometry":
    case "geography":
      return { type: "other", name: base };
    default:
      return null;
  }
}

export function newColumn(name = ""): DesignColumn {
  const column: ColumnDef = {
    name,
    data_type: { type: "text" },
    native_type: "",
    nullable: true,
    auto_increment: false,
    extras: {},
  };
  return { column };
}

export function newIndex(name = ""): IndexDef {
  return { name, columns: [], unique: false, is_constraint: false, extras: {} };
}

export function newForeignKey(design: TableDesign): ForeignKeyDef {
  return {
    columns: [],
    ref_table: {
      kind: "table",
      ...(design.table.catalog ? { catalog: design.table.catalog } : {}),
      ...(design.table.schema ? { schema: design.table.schema } : {}),
      name: "",
    },
    ref_columns: [],
    on_delete: "no_action",
    on_update: "no_action",
    extras: {},
  };
}

function renameIn(list: readonly string[], from: string, to: string): string[] {
  return list.map((c) => (c === from ? to : c));
}

/** Whether a foreign key points at the designed table itself (by its loaded or new name). */
export function isSelfReference(design: TableDesign, fk: ForeignKeyDef): boolean {
  const ref = fk.ref_table;
  const schema = ref.schema ?? design.table.schema;
  if ((schema ?? "") !== (design.table.schema ?? "")) return false;
  return ref.name === design.table.name || ref.name === design.original?.ref.name;
}

/**
 * Renames column `from` to `to` in the primary key, the indexes and the foreign keys
 * (including the referenced columns of a foreign key to this same table). The column itself
 * keeps its origin, so the core generates a rename. Call it once per committed rename, never
 * per keystroke: partial names would capture references of other columns.
 */
export function renameColumnRefs(design: TableDesign, from: string, to: string): TableDesign {
  if (from === to || from === "") return design;
  return {
    ...design,
    ...(design.primaryKey
      ? {
          primaryKey: {
            ...design.primaryKey,
            columns: renameIn(design.primaryKey.columns, from, to),
          },
        }
      : {}),
    indexes: design.indexes.map((item) => ({
      ...item,
      def: {
        ...item.def,
        columns: item.def.columns.map((c) =>
          !c.is_expression && c.name === from ? { ...c, name: to } : c,
        ),
      },
    })),
    foreignKeys: design.foreignKeys.map((item) => ({
      ...item,
      def: {
        ...item.def,
        columns: renameIn(item.def.columns, from, to),
        ...(isSelfReference(design, item.def)
          ? { ref_columns: renameIn(item.def.ref_columns, from, to) }
          : {}),
      },
    })),
  };
}

/** Why column `index` cannot be renamed to `to`, or `null` when it can. */
export function columnNameProblem(design: TableDesign, index: number, to: string): string | null {
  const col = design.columns[index];
  if (!col) return null;
  if (to === "" && col.column.name !== "") return "A column needs a name";
  if (to !== "" && design.columns.some((c, i) => i !== index && c.column.name === to)) {
    return `Another column is already named ${to}`;
  }
  return null;
}

/**
 * Column `index` renamed to `to`, with its primary key, index and foreign key references
 * following it; an error when the name is empty or taken (nothing changes then).
 */
export function renameColumn(
  design: TableDesign,
  index: number,
  to: string,
): { design: TableDesign } | { error: string } {
  const col = design.columns[index];
  if (!col || col.column.name === to) return { design };
  const problem = columnNameProblem(design, index, to);
  if (problem) return { error: problem };
  const renamed: TableDesign = {
    ...design,
    columns: design.columns.map((c, i) =>
      i === index ? { ...c, column: { ...c.column, name: to } } : c,
    ),
  };
  return { design: renameColumnRefs(renamed, col.column.name, to) };
}

/**
 * The design without the references to removed column `name`. Like PostgreSQL's DROP COLUMN,
 * every primary key, index and foreign key that uses the column goes as a whole (a composite
 * key is never silently narrowed to its other columns, which would change its meaning); a
 * foreign key from this table to itself that references the column goes too. Check
 * expressions are not parsed: the preview shows what the database says about them.
 */
export function dropColumnRefs(design: TableDesign, name: string): TableDesign {
  const next: TableDesign = {
    ...design,
    indexes: design.indexes.filter(
      (item) => !item.def.columns.some((c) => !c.is_expression && c.name === name),
    ),
    foreignKeys: design.foreignKeys.filter(
      (item) =>
        !item.def.columns.includes(name) &&
        !(isSelfReference(design, item.def) && item.def.ref_columns.includes(name)),
    ),
  };
  if (design.primaryKey?.columns.includes(name)) delete next.primaryKey;
  return next;
}

/** What removing column `name` also removes (see `dropColumnRefs`), for the user. */
export function dependentsOfColumn(design: TableDesign, name: string): string[] {
  const out: string[] = [];
  if (design.primaryKey?.columns.includes(name)) {
    out.push(`the primary key (${design.primaryKey.columns.join(", ")})`);
  }
  for (const item of design.indexes) {
    if (item.def.columns.some((c) => !c.is_expression && c.name === name)) {
      out.push(`${item.def.unique ? "unique index" : "index"} ${item.def.name || "(unnamed)"}`);
    }
  }
  for (const item of design.foreignKeys) {
    const self = isSelfReference(design, item.def) && item.def.ref_columns.includes(name);
    if (item.def.columns.includes(name) || self) {
      out.push(`foreign key ${item.def.name || `(${item.def.columns.join(", ")})`}`);
    }
  }
  return out;
}

/** Whether an operation is offered (native or by a rebuild). */
export function allowed(support: Support | undefined): boolean {
  return support !== undefined && support !== "unsupported";
}

/** A hint for an operation done by rebuilding the table. */
export function supportHint(support: Support | undefined, what: string): string | undefined {
  if (support === "unsupported") return `${what} is not supported by this database`;
  if (support === "rebuild") return `${what} rebuilds the table (data is copied)`;
  return undefined;
}

